export const FIRST_USE_MESSAGE = '开始记忆前，先给这只大肥鱼选一个记忆空间。不同的鱼请选择不同空间；同一只鱼换会话，请选回原空间。';

export function onboardingPrompt(roomEnabled = true) {
  return [
    '【大肥鱼记忆：首次使用，尚未选择空间】',
    FIRST_USE_MESSAGE,
    roomEnabled
      ? '请在本轮回复中简短提醒用户，并调用 hp_space 获取当前会话的设置链接，把完整链接交给用户亲自选择和确认。'
      : '请在本轮回复中提醒用户：空间选择入口已关闭，需要启用插件的 roomEnabled 后再调用 hp_space 选择空间。',
    '可以继续普通聊天，但选择完成前不要写入、导入或声称已读取任何记忆；不要自行绑定、猜测人格归属或修改绑定文件。',
    '只有一只鱼可选“记忆空间1”；另一只鱼可选“记忆空间2”。旧记忆需先核对归属，不能自动混合导入。',
    '用户确认完成后再次调用 hp_space 核对；不要编造设置链接，也不要循环调用工具。',
  ].join('\n');
}
