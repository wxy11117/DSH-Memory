#!/usr/bin/env node
// Standalone demo host. Never edits a DSH profile or uses a live memory directory.
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import readline from 'node:readline';
import {spawn} from 'node:child_process';
import {mount,bind} from '../tests/helpers/room-host.mjs';
const home=fs.mkdtempSync(path.join(os.tmpdir(),'hp-room-demo-'));
const host=mount({homeDir:home});
const spaces={a:'记忆空间1',b:'记忆空间2'};
for(const [id,space]of Object.entries(spaces)){
  const url=await bind(host,id,space);
  await host.call(id,'hp_remember',{text:id==='a'?'演示资料：这只鱼喜欢海风和暖色灯光。':'演示资料：这只鱼喜欢星空和安静的钢琴。',category:'self',source:'demo'});
  console.log(JSON.stringify({demo:true,fish:id,space,url}));
  if(id==='a'&&process.argv.includes('--open')){
    // The URL is generated by our own local service, never passed to a shell.
    const child=process.platform==='win32'?spawn('rundll32.exe',['url.dll,FileProtocolHandler',url],{windowsHide:true,stdio:'ignore'}):spawn(process.platform==='darwin'?'open':'xdg-open',[url],{stdio:'ignore'});
    child.on('error',()=>console.log('请手动复制上方完整链接到浏览器。'));child.unref();
  }
}
console.log('独立演示已启动，数据仅在临时目录：'+home);
console.log('可在此输入 JSON 模拟 AI 工具，例如 {"fish":"a","action":"light","on":true}；{"fish":"a","state":true} 查看结果。关闭此窗口即可停止。');
const keepAlive=setInterval(()=>{},30000);
const input=readline.createInterface({input:process.stdin,output:process.stdout});
input.on('line',async line=>{try{const {fish='a',state,...command}=JSON.parse(line);if(!Object.hasOwn(spaces,fish))throw new Error('只支持演示鱼 a / b');console.log(JSON.stringify(await host.call(fish,state?'hp_room_state':'hp_room_action',command)))}catch(e){console.log(JSON.stringify({ok:false,error:e.message}))}});
let stopping=false;
async function stop(){if(stopping)return;stopping=true;clearInterval(keepAlive);input.close();await host.close();process.exit(0)}
process.on('SIGINT',stop);process.on('SIGTERM',stop);
input.on('SIGINT',stop);input.on('close',stop);
